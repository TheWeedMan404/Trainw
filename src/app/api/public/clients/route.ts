import { NextRequest, NextResponse } from "next/server";
import { z } from "zod";

import { verifyCaptcha } from "@/lib/captcha";
import { isSupabaseAdminConfigured } from "@/lib/env";
import { checkRateLimit, getRequestIp } from "@/lib/rate-limit";
import { createAdminSupabaseClient } from "@/lib/supabase/admin";

// NX-05 (Phase 1b): public client registration is now a pending queue,
// not a direct insert.
//   * Rate limited (10/min per IP) + CAPTCHA (hCaptcha; fail-open with a
//     loud warning only while CAPTCHA_SECRET_KEY is unset — see
//     src/lib/captcha.ts; the endpoint must not go live without it).
//   * Requires an email OR a phone (zod refine), plus a confirmation step
//     (see below).
//   * Individual-type registrations must not carry a gymId (NX-21).
//   * Inserts with status='pending'. The client_code is generated by the
//     DB trigger at insert but is NOT returned here — it is issued (shown)
//     only when the gym approves the registration in the dashboard.
//   * Never returns Supabase error text (NX-15).
//
// Confirmation step: a true email-confirmation token flow needs an email
// provider + a token table, which is Phase 2. The step shipped here is
// the gym-side approval queue: nothing becomes an active client until a
// gym manager approves it (approveWorkspaceClientAction), and the
// contact (email/phone) is stored for the gym to reach the registrant.
// contact_verified stays false until that Phase 2 flow lands.
// The status/email/phone/contact_verified columns come from migration
// 20261115090000_phase1b_public_clients_status.sql (guarded: it only
// applies when the clients table exists — the table lives in
// database/schema.sql, P1-11 territory).

const registerClientSchema = z
  .object({
    captchaToken: z.string().optional(),
    email: z.string().email().optional(),
    gymId: z.string().uuid().nullable(),
    name: z.string().min(2),
    phone: z.string().min(6).max(30).optional(),
    type: z.enum(["gym", "individual"]),
  })
  .refine((data) => data.email || data.phone, {
    message: "Provide an email address or a phone number.",
  })
  .refine((data) => data.type !== "individual" || !data.gymId, {
    message: "Individual clients must not select a gym.",
  });

export async function POST(request: NextRequest) {
  if (!isSupabaseAdminConfigured()) {
    return NextResponse.json(
      { error: "Registration is unavailable right now." },
      { status: 503 },
    );
  }

  // NX-01: rate-limit before any other work (10/min per IP).
  const clientIp = getRequestIp(request.headers);
  const rateLimit = checkRateLimit(`public-clients:ip:${clientIp}`, 10, 60 * 1000);
  if (!rateLimit.allowed) {
    return NextResponse.json(
      { error: "Too many registration attempts. Please try again later." },
      {
        headers: { "Retry-After": String(rateLimit.retryAfterSeconds) },
        status: 429,
      },
    );
  }

  // NX-22: malformed JSON is a 400, not a 500.
  let body: unknown;
  try {
    body = await request.json();
  } catch {
    return NextResponse.json(
      { error: "Please provide a valid client name and registration type." },
      { status: 400 },
    );
  }

  const payload = registerClientSchema.safeParse(body);

  if (!payload.success) {
    return NextResponse.json(
      { error: "Please provide a valid client name and registration type." },
      { status: 400 },
    );
  }

  // NX-05: CAPTCHA before the insert. When the secret is unset the check
  // fails open with a warning (local dev only — see captcha.ts).
  const captcha = await verifyCaptcha(payload.data.captchaToken, clientIp);
  if (!captcha.ok) {
    return NextResponse.json(
      { error: "Please complete the CAPTCHA and try again." },
      { status: 400 },
    );
  }

  if (payload.data.type === "gym" && !payload.data.gymId) {
    return NextResponse.json(
      { error: "Gym-linked clients must select a gym." },
      { status: 400 },
    );
  }

  const admin = createAdminSupabaseClient();

  let gymName: string | null = null;

  if (payload.data.gymId) {
    const { data: gym, error: gymError } = await admin
      .from("gyms")
      .select("id, name")
      .eq("id", payload.data.gymId)
      .maybeSingle();

    if (gymError || !gym) {
      return NextResponse.json({ error: "Selected gym was not found." }, { status: 404 });
    }

    gymName = gym.name;
  }

  const { error } = await admin
    .from("clients")
    .insert({
      contact_verified: false,
      email: payload.data.email ?? null,
      gym_id: payload.data.gymId,
      name: payload.data.name,
      phone: payload.data.phone ?? null,
      status: "pending",
      type: payload.data.type,
    })
    .select("id")
    .single();

  if (error) {
    // NX-15: generic message — never Supabase's error text.
    return NextResponse.json(
      { error: "Unable to create the client registration right now." },
      { status: 500 },
    );
  }

  return NextResponse.json({
    gymName,
    message:
      "Registration received. The gym will review it and issue your client code.",
  });
}
