"use server";

import { revalidatePath } from "next/cache";
import { z } from "zod";

import { type FormState, getErrorMessage } from "@/actions/shared";
import { PERMISSIONS } from "@/lib/permissions";
import { createServerSupabaseClient } from "@/lib/supabase/server";
import { requirePermission } from "@/lib/workspace";

const createClientSchema = z.object({
  name: z.string().min(2),
  type: z.enum(["gym", "individual"]),
});

export async function createWorkspaceClientAction(
  _previousState: FormState,
  formData: FormData,
): Promise<FormState> {
  const context = await requirePermission(PERMISSIONS.clientsManage);
  const parsed = createClientSchema.safeParse({
    name: formData.get("name"),
    type: formData.get("type"),
  });

  if (!parsed.success) {
    return { error: "Enter a client name and choose the client type." };
  }

  try {
    const supabase = await createServerSupabaseClient();
    const { error } = await supabase.from("clients").insert({
      gym_id: context.gymId,
      name: parsed.data.name,
      type: parsed.data.type,
    });

    if (error) {
      return { error: error.message };
    }
  } catch (error) {
    return { error: getErrorMessage(error, "Unable to create the client.") };
  }

  revalidatePath("/dashboard");
  revalidatePath("/dashboard/clients");
  revalidatePath("/dashboard/classes");

  return { success: "Client created successfully." };
}

const updateClientSchema = z.object({
  clientId: z.string().uuid(),
  name: z.string().min(2).max(100),
  type: z.enum(["gym", "individual"]),
});

// NX-10: edit a client record. Gym-scoped: only this gym's rows, and the
// row must exist (a silent no-op would hide a stale form or a wrong id).
export async function updateWorkspaceClientAction(
  _previousState: FormState,
  formData: FormData,
): Promise<FormState> {
  const context = await requirePermission(PERMISSIONS.clientsManage);
  const parsed = updateClientSchema.safeParse({
    clientId: formData.get("clientId"),
    name: formData.get("name"),
    type: formData.get("type"),
  });

  if (!parsed.success) {
    return { error: "Enter a client name and choose the client type." };
  }

  try {
    const supabase = await createServerSupabaseClient();
    const { data, error } = await supabase
      .from("clients")
      .update({ name: parsed.data.name, type: parsed.data.type })
      .eq("id", parsed.data.clientId)
      .eq("gym_id", context.gymId)
      .select("id")
      .maybeSingle();

    if (error) {
      return { error: error.message };
    }
    if (!data) {
      return { error: "That client no longer exists in your workspace." };
    }
  } catch (error) {
    return { error: getErrorMessage(error, "Unable to update the client.") };
  }

  revalidatePath("/dashboard");
  revalidatePath("/dashboard/clients");
  revalidatePath("/dashboard/classes");

  return { success: "Client updated." };
}

// NX-05: approve a pending public registration. The client_code was
// generated by the DB trigger at insert, but it is only revealed to the
// gym (in the dashboard list) once the registration is approved — the
// public endpoint never returns it.
export async function approveWorkspaceClientAction(
  _previousState: FormState,
  formData: FormData,
): Promise<FormState> {
  const context = await requirePermission(PERMISSIONS.clientsManage);
  const clientId = String(formData.get("clientId") ?? "");

  if (!clientId) {
    return { error: "No client was selected." };
  }

  try {
    const supabase = await createServerSupabaseClient();
    const { data, error } = await supabase
      .from("clients")
      .update({ status: "approved" })
      .eq("id", clientId)
      .eq("gym_id", context.gymId)
      .eq("status", "pending")
      .select("id")
      .maybeSingle();

    if (error) {
      return { error: error.message };
    }
    if (!data) {
      return { error: "That registration is no longer pending." };
    }
  } catch (error) {
    return { error: getErrorMessage(error, "Unable to approve the client.") };
  }

  revalidatePath("/dashboard");
  revalidatePath("/dashboard/clients");

  return { success: "Client approved." };
}

// NX-05: gym-side delete for a client record (including a pending
// registration the gym does not want). Gym-scoped: only this gym's rows.
export async function deleteWorkspaceClientAction(
  _previousState: FormState,
  formData: FormData,
): Promise<FormState> {
  const context = await requirePermission(PERMISSIONS.clientsManage);
  const clientId = String(formData.get("clientId") ?? "");

  if (!clientId) {
    return { error: "No client was selected." };
  }

  try {
    const supabase = await createServerSupabaseClient();
    const { error } = await supabase
      .from("clients")
      .delete()
      .eq("id", clientId)
      .eq("gym_id", context.gymId);

    if (error) {
      return { error: error.message };
    }
  } catch (error) {
    return { error: getErrorMessage(error, "Unable to delete the client.") };
  }

  revalidatePath("/dashboard");
  revalidatePath("/dashboard/clients");
  revalidatePath("/dashboard/classes");

  return { success: "Client deleted." };
}
